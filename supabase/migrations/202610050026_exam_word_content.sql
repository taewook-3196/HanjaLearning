-- Source-verifiable original content for word/context exam generation.
-- Do not copy official past-paper sentences into these tables.

create table if not exists public.hanja_word_contexts (
  id bigint generated by default as identity primary key,
  word_id bigint not null references public.hanja_words(id) on delete cascade,
  sentence text not null,
  blank_text text not null,
  content_status text not null default 'DRAFT'
    check (content_status in ('DRAFT','REVIEWED','SOURCE_VERIFIED','PUBLISHED')),
  source_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (length(trim(sentence))>0),
  check (length(trim(blank_text))>0)
);

create table if not exists public.hanja_word_structures (
  word_id bigint primary key references public.hanja_words(id) on delete cascade,
  structure_type text not null
    check (structure_type in ('SUBJECT_PREDICATE','VERB_OBJECT','MODIFIER_HEAD','PARALLEL','OTHER')),
  explanation text,
  content_status text not null default 'DRAFT'
    check (content_status in ('DRAFT','REVIEWED','SOURCE_VERIFIED','PUBLISHED')),
  source_note text,
  updated_at timestamptz not null default now()
);

create table if not exists public.hanja_common_character_sets (
  id bigint generated by default as identity primary key,
  common_hanja_id bigint not null references public.hanja(id) on delete cascade,
  prompt_summary text,
  content_status text not null default 'DRAFT'
    check (content_status in ('DRAFT','REVIEWED','SOURCE_VERIFIED','PUBLISHED')),
  source_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.hanja_common_character_words (
  set_id bigint not null references public.hanja_common_character_sets(id) on delete cascade,
  word_id bigint not null references public.hanja_words(id) on delete cascade,
  primary key (set_id,word_id)
);

create index if not exists idx_hanja_word_contexts_word_status
  on public.hanja_word_contexts(word_id,content_status);
create index if not exists idx_hanja_word_structures_status
  on public.hanja_word_structures(content_status);
create index if not exists idx_hanja_common_sets_status
  on public.hanja_common_character_sets(content_status);

alter table public.hanja_word_contexts enable row level security;
alter table public.hanja_word_structures enable row level security;
alter table public.hanja_common_character_sets enable row level security;
alter table public.hanja_common_character_words enable row level security;

revoke all on public.hanja_word_contexts,public.hanja_word_structures,public.hanja_common_character_sets,public.hanja_common_character_words from anon,authenticated;
grant select on public.hanja_word_contexts,public.hanja_word_structures,public.hanja_common_character_sets,public.hanja_common_character_words to authenticated;

create policy "authenticated read published word contexts" on public.hanja_word_contexts
 for select to authenticated using (
  content_status='PUBLISHED'
  and exists(select 1 from public.hanja_words w where w.id=word_id and w.content_status='PUBLISHED')
 );

create policy "authenticated read published word structures" on public.hanja_word_structures
 for select to authenticated using (
  content_status='PUBLISHED'
  and exists(select 1 from public.hanja_words w where w.id=word_id and w.content_status='PUBLISHED')
 );

create policy "authenticated read published common character sets" on public.hanja_common_character_sets
 for select to authenticated using (
  content_status='PUBLISHED'
  and exists(select 1 from public.hanja h where h.id=common_hanja_id and h.content_status='PUBLISHED')
 );

create policy "authenticated read words of published common character sets" on public.hanja_common_character_words
 for select to authenticated using (
  exists(select 1 from public.hanja_common_character_sets s where s.id=set_id and s.content_status='PUBLISHED')
  and exists(select 1 from public.hanja_words w where w.id=word_id and w.content_status='PUBLISHED')
 );

comment on table public.hanja_word_contexts is 'Original reviewed example sentences for context-style exam questions; not copied past-paper text.';
comment on table public.hanja_word_structures is 'Reviewed semantic/syntactic structure classification for Hanja words.';
comment on table public.hanja_common_character_sets is 'Reviewed common-character question sets linked to published Hanja words.';
