create table if not exists public.exam_specs (
  id bigint generated by default as identity primary key,
  grade_id bigint not null references public.exam_grades(id) on delete cascade,
  exam_mode text not null check (exam_mode in ('FIELD','ONLINE')),
  question_count integer not null check (question_count > 0),
  time_limit_minutes integer not null check (time_limit_minutes > 0),
  passing_percent integer not null check (passing_percent between 1 and 100),
  objective_count integer not null default 0 check (objective_count >= 0),
  subjective_count integer not null default 0 check (subjective_count >= 0),
  source_year integer not null,
  source_url text not null,
  verified_at date not null default current_date,
  unique (grade_id, exam_mode),
  check (objective_count + subjective_count = question_count)
);

alter table public.exam_specs enable row level security;
revoke all on public.exam_specs from anon, authenticated;
grant select on public.exam_specs to authenticated;

create policy "authenticated read exam specs" on public.exam_specs
  for select to authenticated using (true);
