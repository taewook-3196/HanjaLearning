-- Verified relationships between published Hanja words.
-- No relation is exposed to learners until it has been source-verified and published.
create table if not exists public.hanja_word_relations (
  id bigint generated by default as identity primary key,
  from_word_id bigint not null references public.hanja_words(id) on delete cascade,
  to_word_id bigint not null references public.hanja_words(id) on delete cascade,
  relation_type text not null check (relation_type in ('SIMILAR','OPPOSITE')),
  content_status text not null default 'DRAFT'
    check (content_status in ('DRAFT','REVIEWED','SOURCE_VERIFIED','PUBLISHED')),
  source_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (from_word_id,to_word_id,relation_type),
  check (from_word_id<to_word_id)
);

create index if not exists idx_hanja_word_relations_from
  on public.hanja_word_relations(from_word_id);
create index if not exists idx_hanja_word_relations_type_status
  on public.hanja_word_relations(relation_type,content_status);

alter table public.hanja_word_relations enable row level security;
revoke all on public.hanja_word_relations from anon,authenticated;
grant select on public.hanja_word_relations to authenticated;

create policy "authenticated read published word relations"
  on public.hanja_word_relations
  for select to authenticated
  using (
    content_status='PUBLISHED'
    and exists (
      select 1 from public.hanja_words w
      where w.id=from_word_id and w.content_status='PUBLISHED'
    )
    and exists (
      select 1 from public.hanja_words w
      where w.id=to_word_id and w.content_status='PUBLISHED'
    )
  );

comment on table public.hanja_word_relations is
  'Source-verifiable synonym/antonym relationships between Hanja words used for exam generation. Store each unordered pair once with from_word_id < to_word_id.';
