create table if not exists public.feedback_tickets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null check (category in ('CONTENT_ERROR','BUG','SUGGESTION','OTHER')),
  title text not null check (char_length(trim(title)) between 1 and 120),
  status text not null default 'NEW' check (status in ('NEW','IN_PROGRESS','RESOLVED')),
  context jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.feedback_messages (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.feedback_tickets(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(trim(body)) between 1 and 4000),
  created_at timestamptz not null default now()
);
create index if not exists feedback_tickets_user_created_idx on public.feedback_tickets(user_id,created_at desc);
create index if not exists feedback_tickets_status_created_idx on public.feedback_tickets(status,created_at desc);
create index if not exists feedback_messages_ticket_created_idx on public.feedback_messages(ticket_id,created_at);

alter table public.feedback_tickets enable row level security;
alter table public.feedback_messages enable row level security;

create policy feedback_tickets_select_own_or_admin on public.feedback_tickets for select
using (user_id=(select auth.uid()) or public.is_app_admin());
create policy feedback_tickets_insert_own on public.feedback_tickets for insert
with check (user_id=(select auth.uid()));
create policy feedback_tickets_admin_update on public.feedback_tickets for update
using (public.is_app_admin()) with check (public.is_app_admin());

create policy feedback_messages_select_ticket_participant on public.feedback_messages for select
using (exists(select 1 from public.feedback_tickets t where t.id=ticket_id and (t.user_id=(select auth.uid()) or public.is_app_admin())));
create policy feedback_messages_insert_ticket_participant on public.feedback_messages for insert
with check (
 sender_id=(select auth.uid()) and
 exists(select 1 from public.feedback_tickets t where t.id=ticket_id and (t.user_id=(select auth.uid()) or public.is_app_admin()))
);

create or replace function public.create_feedback_ticket(
  target_category text, target_title text, target_body text, target_context jsonb default '{}'::jsonb
) returns bigint language plpgsql security invoker set search_path=public as $$
declare new_id bigint;
begin
  if target_category not in ('CONTENT_ERROR','BUG','SUGGESTION','OTHER') then raise exception 'invalid category'; end if;
  insert into public.feedback_tickets(user_id,category,title,context)
  values ((select auth.uid()),target_category,trim(target_title),coalesce(target_context,'{}'::jsonb))
  returning id into new_id;
  insert into public.feedback_messages(ticket_id,sender_id,body)
  values (new_id,(select auth.uid()),trim(target_body));
  return new_id;
end $$;

create or replace function public.touch_feedback_ticket() returns trigger language plpgsql set search_path=public as $$
begin update public.feedback_tickets set updated_at=now() where id=new.ticket_id; return new; end $$;
drop trigger if exists feedback_message_touch_ticket on public.feedback_messages;
create trigger feedback_message_touch_ticket after insert on public.feedback_messages for each row execute function public.touch_feedback_ticket();
