create table if not exists public.exam_attempts (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 grade_id bigint not null references public.exam_grades(id),
 exam_mode text not null check (exam_mode in ('FIELD','ONLINE')),
 question_count integer not null check (question_count > 0),
 correct_count integer not null default 0 check (correct_count >= 0 and correct_count <= question_count),
 score_percent integer not null default 0 check (score_percent between 0 and 100),
 passed boolean not null default false,
 started_at timestamptz not null default now(),
 submitted_at timestamptz
);
create table if not exists public.exam_attempt_questions (
 id bigint generated by default as identity primary key,
 attempt_id bigint not null references public.exam_attempts(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 position integer not null check (position > 0),
 question_key text not null,
 question_type text not null,
 answered_correctly boolean,
 unique(attempt_id,position)
);
alter table public.exam_attempts enable row level security;
alter table public.exam_attempt_questions enable row level security;
revoke all on public.exam_attempts,public.exam_attempt_questions from anon,authenticated;
grant select,insert,update on public.exam_attempts to authenticated;
grant select,insert,update on public.exam_attempt_questions to authenticated;
create policy exam_attempts_select_own on public.exam_attempts for select to authenticated using ((select auth.uid())=user_id);
create policy exam_attempts_insert_own on public.exam_attempts for insert to authenticated with check ((select auth.uid())=user_id);
create policy exam_attempts_update_own on public.exam_attempts for update to authenticated using ((select auth.uid())=user_id) with check ((select auth.uid())=user_id);
create policy exam_attempt_questions_select_own on public.exam_attempt_questions for select to authenticated using ((select auth.uid())=user_id);
create policy exam_attempt_questions_insert_own on public.exam_attempt_questions for insert to authenticated with check ((select auth.uid())=user_id);
create policy exam_attempt_questions_update_own on public.exam_attempt_questions for update to authenticated using ((select auth.uid())=user_id) with check ((select auth.uid())=user_id);
create index if not exists idx_exam_attempts_user_submitted on public.exam_attempts(user_id,submitted_at desc);
create index if not exists idx_exam_attempt_questions_user_key on public.exam_attempt_questions(user_id,question_key);
