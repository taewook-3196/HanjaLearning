create table if not exists public.user_gift_request_rewards (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 milestone_level integer not null check (milestone_level >= 5 and milestone_level % 5 = 0),
 earned_at timestamptz not null default now(),
 used_at timestamptz,
 unique(user_id,milestone_level)
);
alter table public.user_gift_request_rewards enable row level security;
grant select on public.user_gift_request_rewards to authenticated;
create policy "users read own gift request rewards" on public.user_gift_request_rewards for select to authenticated using ((select auth.uid())=user_id);

create or replace function public.award_gift_request_rewards(p_user_id uuid)
returns void language plpgsql security definer set search_path=public as $$
declare total_xp integer; current_level integer; milestone integer;
begin
 if p_user_id is null then return; end if;
 select coalesce(sum(xp),0)::integer into total_xp from public.user_xp_events where user_id=p_user_id;
 current_level:=case when total_xp<5000 then floor(sqrt(total_xp/50.0))::integer+1 else 11+floor((total_xp-5000)/1000.0)::integer end;
 milestone:=5;
 while milestone<=current_level loop
  insert into public.user_gift_request_rewards(user_id,milestone_level) values(p_user_id,milestone) on conflict do nothing;
  milestone:=milestone+5;
 end loop;
end $$;
revoke all on function public.award_gift_request_rewards(uuid) from public,anon,authenticated;

create or replace function public.reward_after_xp_event()
returns trigger language plpgsql security definer set search_path=public as $$
begin perform public.award_gift_request_rewards(new.user_id); return new; end $$;
revoke all on function public.reward_after_xp_event() from public,anon,authenticated;
drop trigger if exists reward_after_xp_event on public.user_xp_events;
create trigger reward_after_xp_event after insert or update of xp on public.user_xp_events for each row execute function public.reward_after_xp_event();

