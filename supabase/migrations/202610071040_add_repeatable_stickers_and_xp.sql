create table if not exists public.user_repeatable_sticker_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  sticker_key text not null check (sticker_key in ('daily_perfect','daily_plan','daily_review')),
  earned_on date not null,
  earned_at timestamptz not null default now(),
  celebrated_at timestamptz,
  unique (user_id, sticker_key, earned_on)
);
alter table public.user_repeatable_sticker_events enable row level security;
create policy "users read own repeatable sticker events" on public.user_repeatable_sticker_events for select to authenticated using (auth.uid()=user_id);
create policy "users earn own repeatable sticker events" on public.user_repeatable_sticker_events for insert to authenticated with check (auth.uid()=user_id);
create policy "users update own repeatable sticker events" on public.user_repeatable_sticker_events for update to authenticated using (auth.uid()=user_id) with check (auth.uid()=user_id);
grant select,insert,update on public.user_repeatable_sticker_events to authenticated;
grant usage,select on sequence public.user_repeatable_sticker_events_id_seq to authenticated;

create table if not exists public.user_xp_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_key text not null,
  event_date date not null,
  xp integer not null check (xp > 0 and xp <= 500),
  reason text not null,
  created_at timestamptz not null default now(),
  unique (user_id,event_key,event_date)
);
alter table public.user_xp_events enable row level security;
create policy "users read own xp events" on public.user_xp_events for select to authenticated using (auth.uid()=user_id);
create policy "users earn own xp events" on public.user_xp_events for insert to authenticated with check (auth.uid()=user_id);
grant select,insert on public.user_xp_events to authenticated;
grant usage,select on sequence public.user_xp_events_id_seq to authenticated;
