-- Structured metadata required for official-style mock exam question types.
-- Keep facts source-verifiable; do not store copied past-paper questions.

create table if not exists public.hanja_exam_metadata (
  hanja_id bigint primary key references public.hanja(id) on delete cascade,
  radical text,
  total_strokes integer check (total_strokes is null or total_strokes > 0),
  formation_type text check (formation_type is null or formation_type in ('PICTOGRAPH','IDEOGRAPH','COMPOUND_IDEOGRAPH','PHONO_SEMANTIC','LOAN','DERIVATIVE')),
  content_status text not null default 'DRAFT'
    check (content_status in ('DRAFT','REVIEWED','SOURCE_VERIFIED','PUBLISHED')),
  source_note text,
  updated_at timestamptz not null default now()
);

create table if not exists public.hanja_idioms (
  id bigint generated by default as identity primary key,
  idiom text not null unique,
  reading text,
  meaning text not null,
  child_explanation text,
  content_status text not null default 'DRAFT'
    check (content_status in ('DRAFT','REVIEWED','SOURCE_VERIFIED','PUBLISHED')),
  source_note text
);

create table if not exists public.hanja_idiom_map (
  idiom_id bigint not null references public.hanja_idioms(id) on delete cascade,
  hanja_id bigint not null references public.hanja(id) on delete cascade,
  position integer not null check (position between 1 and 4),
  primary key (idiom_id, position)
);

create table if not exists public.exam_culture_items (
  id bigint generated by default as identity primary key,
  provider_id bigint not null references public.exam_providers(id) on delete cascade,
  grade_id bigint not null references public.exam_grades(id) on delete cascade,
  topic text not null,
  prompt_summary text not null,
  correct_explanation text not null,
  content_status text not null default 'DRAFT'
    check (content_status in ('DRAFT','REVIEWED','SOURCE_VERIFIED','PUBLISHED')),
  source_note text
);

alter table public.hanja_exam_metadata enable row level security;
alter table public.hanja_idioms enable row level security;
alter table public.hanja_idiom_map enable row level security;
alter table public.exam_culture_items enable row level security;

revoke all on public.hanja_exam_metadata, public.hanja_idioms, public.hanja_idiom_map, public.exam_culture_items from anon, authenticated;
grant select on public.hanja_exam_metadata, public.hanja_idioms, public.hanja_idiom_map, public.exam_culture_items to authenticated;

create policy "authenticated read published exam metadata" on public.hanja_exam_metadata
  for select to authenticated using (content_status='PUBLISHED');
create policy "authenticated read published idioms" on public.hanja_idioms
  for select to authenticated using (content_status='PUBLISHED');
create policy "authenticated read published idiom maps" on public.hanja_idiom_map
  for select to authenticated using (
    exists (select 1 from public.hanja_idioms i where i.id=idiom_id and i.content_status='PUBLISHED')
  );
create policy "authenticated read published culture items" on public.exam_culture_items
  for select to authenticated using (
    content_status='PUBLISHED'
    and exists (
      select 1 from public.exam_grades g
      where g.id=grade_id and g.provider_id=exam_culture_items.provider_id
    )
  );

create index if not exists idx_hanja_idiom_map_hanja on public.hanja_idiom_map(hanja_id);
create index if not exists idx_exam_culture_provider_grade on public.exam_culture_items(provider_id,grade_id);
