create table public.direct_messages (
 id bigint generated by default as identity primary key,
 sender_id uuid not null references auth.users(id) on delete cascade,
 recipient_id uuid not null references auth.users(id) on delete cascade,
 body text not null check (char_length(btrim(body)) between 1 and 1000),
 read_at timestamptz,
 created_at timestamptz not null default now(),
 check (sender_id <> recipient_id)
);
create index direct_messages_conversation_idx on public.direct_messages(sender_id,recipient_id,created_at desc);
create index direct_messages_recipient_unread_idx on public.direct_messages(recipient_id,read_at,created_at desc);
alter table public.direct_messages enable row level security;
create policy direct_messages_participant_select on public.direct_messages for select using ((select auth.uid())=sender_id or (select auth.uid())=recipient_id);
create policy direct_messages_friend_insert on public.direct_messages for insert with check (
 (select auth.uid())=sender_id and exists(
  select 1 from public.friendships f where f.status='ACCEPTED' and
  ((f.requester_id=sender_id and f.addressee_id=recipient_id) or (f.requester_id=recipient_id and f.addressee_id=sender_id))
 )
);
create or replace function public.mark_friend_messages_read(friend_user_id uuid) returns void language sql security invoker set search_path=public as $$
 update public.direct_messages set read_at=now() where recipient_id=(select auth.uid()) and sender_id=friend_user_id and read_at is null;
$$;
create or replace function public.friend_unread_message_count() returns bigint language sql stable security invoker set search_path=public as $$
 select count(*) from public.direct_messages where recipient_id=(select auth.uid()) and read_at is null;
$$;