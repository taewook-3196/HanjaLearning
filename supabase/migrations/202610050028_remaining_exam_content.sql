-- Verified source data for remaining official-style question types.
-- Illustration assets must be original/app-owned; never store copied past-paper images.

create table if not exists public.hanja_usage_items (
  id bigint generated by default as identity primary key,
  hanja_id bigint not null references public.hanja(id) on delete cascade,
  prompt text not null,
  choice_a text not null, choice_b text not null, choice_c text not null, choice_d text not null,
  correct_choice smallint not null check (correct_choice between 1 and 4),
  content_status text not null default 'DRAFT'
    check (content_status in ('DRAFT','REVIEWED','SOURCE_VERIFIED','PUBLISHED')),
  source_note text,
  check (btrim(choice_a)<>btrim(choice_b) and btrim(choice_a)<>btrim(choice_c) and btrim(choice_a)<>btrim(choice_d) and btrim(choice_b)<>btrim(choice_c) and btrim(choice_b)<>btrim(choice_d) and btrim(choice_c)<>btrim(choice_d))
);

create table if not exists public.hanja_special_readings (
  id bigint generated by default as identity primary key,
  hanja_id bigint not null references public.hanja(id) on delete cascade,
  reading text not null,
  meaning text not null,
  usage_note text not null,
  choice_a text not null, choice_b text not null, choice_c text not null, choice_d text not null,
  correct_choice smallint not null check (correct_choice between 1 and 4),
  content_status text not null default 'DRAFT'
    check (content_status in ('DRAFT','REVIEWED','SOURCE_VERIFIED','PUBLISHED')),
  source_note text,
  unique(hanja_id,reading,meaning),
  check (length(trim(usage_note))>0),
  check (btrim(choice_a)<>btrim(choice_b) and btrim(choice_a)<>btrim(choice_c) and btrim(choice_a)<>btrim(choice_d) and btrim(choice_b)<>btrim(choice_c) and btrim(choice_b)<>btrim(choice_d) and btrim(choice_c)<>btrim(choice_d))
);

create table if not exists public.hanja_image_items (
  id bigint generated by default as identity primary key,
  hanja_id bigint not null references public.hanja(id) on delete cascade,
  asset_path text not null,
  alt_text text not null,
  asset_license text not null check (asset_license in ('APP_ORIGINAL','CC0')),
  content_status text not null default 'DRAFT'
    check (content_status in ('DRAFT','REVIEWED','SOURCE_VERIFIED','PUBLISHED')),
  source_note text,
  unique(asset_path),
  check (asset_path like '/exam-images/%'),
  check (asset_path !~ '(^|/)\\.\\.(/|$)' and asset_path !~ '^//'),
  check (position('?' in asset_path)=0 and position('#' in asset_path)=0 and position('\\\\' in asset_path)=0),
  check (length(trim(alt_text))>0)
);

alter table public.hanja_usage_items enable row level security;
alter table public.hanja_special_readings enable row level security;
alter table public.hanja_image_items enable row level security;
revoke all on public.hanja_usage_items,public.hanja_special_readings,public.hanja_image_items from anon,authenticated;
grant select on public.hanja_usage_items,public.hanja_special_readings,public.hanja_image_items to authenticated;

create policy "authenticated read published usage items" on public.hanja_usage_items
 for select to authenticated using (content_status='PUBLISHED' and exists(select 1 from public.hanja h where h.id=hanja_id and h.content_status='PUBLISHED'));
create policy "authenticated read published special readings" on public.hanja_special_readings
 for select to authenticated using (content_status='PUBLISHED' and exists(select 1 from public.hanja h where h.id=hanja_id and h.content_status='PUBLISHED'));
create policy "authenticated read published original image items" on public.hanja_image_items
 for select to authenticated using (content_status='PUBLISHED' and asset_license in ('APP_ORIGINAL','CC0') and exists(select 1 from public.hanja h where h.id=hanja_id and h.content_status='PUBLISHED'));

create index if not exists idx_hanja_usage_status on public.hanja_usage_items(hanja_id,content_status);
create index if not exists idx_hanja_special_reading_status on public.hanja_special_readings(hanja_id,content_status);
create index if not exists idx_hanja_image_status on public.hanja_image_items(hanja_id,content_status);
