-- Task 3: shared Hanja content schema
-- User learning records remain isolated in the Task 2 tables.
-- Only PUBLISHED content is readable by the app.

create table if not exists public.exam_providers (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.exam_grades (
  id bigint generated by default as identity primary key,
  provider_id bigint not null references public.exam_providers(id) on delete cascade,
  code text not null,
  name text not null,
  cumulative_hanja_count integer check (cumulative_hanja_count is null or cumulative_hanja_count >= 0),
  sort_order integer not null default 0,
  unique (provider_id, code)
);

create table if not exists public.hanja (
  id bigint generated by default as identity primary key,
  character text not null unique check (char_length(character) = 1),
  primary_meaning text,
  primary_reading text,
  content_status text not null default 'DRAFT'
    check (content_status in ('DRAFT','REVIEWED','SOURCE_VERIFIED','PUBLISHED')),
  source_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.grade_hanja (
  grade_id bigint not null references public.exam_grades(id) on delete cascade,
  hanja_id bigint not null references public.hanja(id) on delete cascade,
  sequence_no integer,
  is_new_at_grade boolean not null default false,
  primary key (grade_id, hanja_id)
);

create table if not exists public.hanja_readings (
  id bigint generated by default as identity primary key,
  hanja_id bigint not null references public.hanja(id) on delete cascade,
  reading text not null,
  meaning text,
  is_primary boolean not null default false,
  unique (hanja_id, reading, meaning)
);

create table if not exists public.hanja_words (
  id bigint generated by default as identity primary key,
  word text not null,
  reading text,
  meaning text not null,
  child_explanation text,
  content_status text not null default 'DRAFT'
    check (content_status in ('DRAFT','REVIEWED','SOURCE_VERIFIED','PUBLISHED')),
  source_note text,
  unique (word, reading, meaning)
);

create table if not exists public.hanja_word_map (
  word_id bigint not null references public.hanja_words(id) on delete cascade,
  hanja_id bigint not null references public.hanja(id) on delete cascade,
  position integer not null check (position >= 1),
  primary key (word_id, position),
  unique (word_id, hanja_id, position)
);

create table if not exists public.hanja_relations (
  id bigint generated by default as identity primary key,
  from_hanja_id bigint not null references public.hanja(id) on delete cascade,
  to_hanja_id bigint not null references public.hanja(id) on delete cascade,
  relation_type text not null check (relation_type in ('SIMILAR','OPPOSITE','RELATED','CONFUSABLE')),
  note text,
  unique (from_hanja_id, to_hanja_id, relation_type),
  check (from_hanja_id <> to_hanja_id)
);

create index if not exists idx_grade_hanja_grade_sequence on public.grade_hanja(grade_id, sequence_no);
create index if not exists idx_hanja_readings_hanja on public.hanja_readings(hanja_id);
create index if not exists idx_hanja_word_map_hanja on public.hanja_word_map(hanja_id);
create index if not exists idx_hanja_relations_from on public.hanja_relations(from_hanja_id);

alter table public.exam_providers enable row level security;
alter table public.exam_grades enable row level security;
alter table public.hanja enable row level security;
alter table public.grade_hanja enable row level security;
alter table public.hanja_readings enable row level security;
alter table public.hanja_words enable row level security;
alter table public.hanja_word_map enable row level security;
alter table public.hanja_relations enable row level security;

revoke all on public.exam_providers, public.exam_grades, public.hanja, public.grade_hanja,
  public.hanja_readings, public.hanja_words, public.hanja_word_map, public.hanja_relations
  from anon, authenticated;

grant select on public.exam_providers, public.exam_grades, public.hanja, public.grade_hanja,
  public.hanja_readings, public.hanja_words, public.hanja_word_map, public.hanja_relations
  to authenticated;

create policy "authenticated read exam providers" on public.exam_providers
  for select to authenticated using (true);
create policy "authenticated read exam grades" on public.exam_grades
  for select to authenticated using (true);
create policy "authenticated read published hanja" on public.hanja
  for select to authenticated using (content_status = 'PUBLISHED');
create policy "authenticated read grade mappings" on public.grade_hanja
  for select to authenticated using (
    exists (select 1 from public.hanja h where h.id = hanja_id and h.content_status = 'PUBLISHED')
  );
create policy "authenticated read published readings" on public.hanja_readings
  for select to authenticated using (
    exists (select 1 from public.hanja h where h.id = hanja_id and h.content_status = 'PUBLISHED')
  );
create policy "authenticated read published words" on public.hanja_words
  for select to authenticated using (content_status = 'PUBLISHED');
create policy "authenticated read published word maps" on public.hanja_word_map
  for select to authenticated using (
    exists (select 1 from public.hanja_words w where w.id = word_id and w.content_status = 'PUBLISHED')
    and exists (select 1 from public.hanja h where h.id = hanja_id and h.content_status = 'PUBLISHED')
  );
create policy "authenticated read published relations" on public.hanja_relations
  for select to authenticated using (
    exists (select 1 from public.hanja h where h.id = from_hanja_id and h.content_status = 'PUBLISHED')
    and exists (select 1 from public.hanja h where h.id = to_hanja_id and h.content_status = 'PUBLISHED')
  );
